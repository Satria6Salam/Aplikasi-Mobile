  /// Nama kota/kabupaten yang cocok dengan [words] mulai dari indeks
  /// [start] (dicoba dua kata dulu, mis. "Jakarta Selatan"). Null bila tidak
  /// ada. Perbandingan tidak peka huruf besar.
  static ({String name, int length})? cityAt(List<String> words, int start) {
    if (start >= words.length) return null;
    String norm(String s) => s.toLowerCase().replaceAll(RegExp(r'[^a-z]'), '');
    if (start + 1 < words.length) {
      final String two = '${norm(words[start])} ${norm(words[start + 1])}';
      for (final String c in cities) {
        if (c.toLowerCase() == two) return (name: c, length: 2);
      }
    }
    final String one = norm(words[start]);
    for (final String c in cities) {
      if (c.toLowerCase() == one) return (name: c, length: 1);
    }
    return null;
  }

  /// True bila [word] adalah nama jalan/kawasan yang dikenal.
  static bool isStreet(String word) =>
      streets.contains(word.toLowerCase().replaceAll(RegExp(r'[^a-z]'), ''));
